#!/usr/bin/env node
'use strict';
/**
 * prerender-country-flags.js — write the country-flag tiles into the 17
 * emoji-flag pages at build time.
 *
 * Each of those pages carries its own COUNTRIES registry — already translated
 * into that page's language — and turned it into 195 `.flag-row` tiles with
 * createElement on DOMContentLoaded. So a client that runs no JavaScript saw
 * an empty box where the page's whole payload should be: 15 of the 17 render
 * ZERO tiles without JS (EN and ar carry 8 hand-written ones above the
 * registry). CLAUDE.md's Discovery Model section states the cost — several
 * search and AI crawlers execute none.
 *
 * Same shape as scripts/prerender-collection-grids.js, and deliberately so:
 *
 *   - The markup has ONE owner, `countryFlagRowsHTML` in symbol-explorer.js.
 *     This script calls the shipped renderer through
 *     scripts/lib/collection-grid-engine.js rather than carrying a copy, and
 *     the page's own inline script calls the same function at runtime.
 *   - The arguments are CAPTURED by running the page's own inline script,
 *     never scraped. The per-page aria-label wording is a real translation
 *     decision that lives in the page; this script must not restate it.
 *   - The block is spliced as TEXT between HTML comments, so the file is not
 *     reformatted, and a second run is a no-op.
 *
 * The runtime guard is `.flag-row[data-region]`: generated rows carry that
 * attribute and the hand-written ones above them do not, so a pre-rendered
 * page skips construction without the script mistaking the hand-written tiles
 * for its own output. Getting that predicate wrong is how the earlier
 * "896 of 898" miscount happened — see CLAUDE.md's dated correction.
 *
 * Usage:
 *   node scripts/prerender-country-flags.js                # report only
 *   node scripts/prerender-country-flags.js --write
 *   node scripts/prerender-country-flags.js --write --files a/index.html
 */

const fs = require('fs');
const path = require('path');
const cheerio = require('cheerio');
const { globSync } = require('glob');

const engine = require('./lib/collection-grid-engine.js');
const { anyProxy, captureInlineCalls, spliceInner } = require('./lib/inline-script-capture.js');

const REPO = path.join(__dirname, '..');
const BEGIN = '<!-- BEGIN prerendered country flags: generated by scripts/prerender-country-flags.js, do not edit -->';
const END = '<!-- END prerendered country flags -->';
const BLOCK_RE = /[ \t]*<!--\s*BEGIN prerendered country flags\b[\s\S]*?<!--\s*END prerendered country flags\s*-->\n?/;
const TRIGGER = /\bcountryFlagRowsHTML\s*\(/;
const SENTINEL = ' utg-country-flags ';

/**
 * Run the page's inline script and record the (containerId, countries, aria)
 * it actually rendered with.
 */
function extractCalls(html, lang) {
  const calls = [];
  let pending = null;

  captureInlineCalls(html, {
    lang,
    trigger: TRIGGER,
    // The page calls ns.countryFlagRowsHTML(...) and hands the result to
    // list.insertAdjacentHTML. Capture the arguments here, then attribute
    // them to whichever container the page actually inserted into.
    methods: {
      countryFlagRowsHTML(countries, aria) {
        pending = { countries, aria };
        return SENTINEL;
      },
      isoToFlag: engine.isoToFlag
    },
    elementFor(id) {
      const el = anyProxy();
      return new Proxy(el, {
        get(t, key) {
          if (key === 'insertAdjacentHTML') {
            return (_pos, markup) => {
              if (markup === SENTINEL && pending) {
                calls.push({ containerId: id, countries: pending.countries, aria: pending.aria });
                pending = null;
              }
            };
          }
          // The guard the page runs first — `!list.querySelector(...)` — must
          // report "nothing generated yet" so the insert is reached.
          if (key === 'querySelector') return () => null;
          return t[key];
        }
      });
    }
  });
  return calls;
}

function renderBlock(countries, aria, indent) {
  const rows = countries.map((c) => engine.countryFlagRowsHTML([c], aria));
  return indent + BEGIN + '\n' +
    rows.map((r) => indent + r).join('\n') +
    '\n' + indent + END + '\n';
}

function pagesWithFlags(files) {
  return files.filter((rel) => {
    const abs = path.join(REPO, rel);
    return fs.existsSync(abs) && TRIGGER.test(fs.readFileSync(abs, 'utf8'));
  });
}

function run(opts) {
  const files = opts.files && opts.files.length
    ? opts.files
    : globSync('**/index.html', { cwd: REPO, ignore: ['node_modules/**'] });
  const targets = pagesWithFlags(files).sort();

  let updated = 0, current = 0;
  const errors = [];

  for (const rel of targets) {
    const abs = path.join(REPO, rel);
    const html = fs.readFileSync(abs, 'utf8');
    const $ = cheerio.load(html);
    const lang = ($('html').attr('lang') || 'en').slice(0, 2).toLowerCase();

    let calls;
    try {
      calls = extractCalls(html, lang);
    } catch (err) {
      errors.push(rel + ': inline script would not run (' + err.message + ')');
      continue;
    }
    if (calls.length !== 1) {
      errors.push(rel + ': expected exactly 1 countryFlagRowsHTML insert, saw ' + calls.length);
      continue;
    }
    const { containerId, countries, aria } = calls[0];
    if (!Array.isArray(countries) || !countries.length) {
      errors.push(rel + ': rendered with no countries');
      continue;
    }
    const bad = countries.find((c) => !c || typeof c.name !== 'string' ||
      !/^[A-Za-z]{2}$/.test(String(c.code || '')) || typeof c.region !== 'string');
    if (bad) {
      errors.push(rel + ': a country is missing code/name/region (' + JSON.stringify(bad) + ')');
      continue;
    }

    const next = spliceInner(html, containerId, BLOCK_RE,
      (childIndent) => renderBlock(countries, aria, childIndent));
    if (next === null) {
      errors.push(rel + ': could not locate container #' + containerId + ' in the raw HTML');
      continue;
    }

    // Self-check: the splice appends to the container's existing children and
    // must not disturb them.
    const before = cheerio.load(html.replace(BLOCK_RE, ''))('#' + containerId).children().length;
    const after = cheerio.load(next)('#' + containerId).children().length;
    if (after !== before + countries.length) {
      errors.push(rel + ': splice changed child count to ' + after +
        ', expected ' + (before + countries.length));
      continue;
    }

    if (next === html) { current += 1; continue; }
    updated += 1;
    if (opts.write) fs.writeFileSync(abs, next);
    if (opts.verbose) {
      console.log('  ' + (opts.write ? 'wrote' : 'would write') + ' ' + rel +
        ' (' + countries.length + ' tiles, ' + lang + ')');
    }
  }

  console.log('prerender-country-flags — ' + targets.length + ' page(s) with country flag tiles');
  console.log('  ' + current + ' already current, ' + updated +
    ' ' + (opts.write ? 'updated' : 'would be updated'));
  if (errors.length) {
    console.log('\n  ' + errors.length + ' error(s):');
    for (const e of errors) console.log('    ' + e);
  }
  return { targets: targets.length, updated, current, errors };
}

if (require.main === module) {
  const argv = process.argv.slice(2);
  const write = argv.includes('--write');
  const verbose = argv.includes('--verbose');
  const fi = argv.indexOf('--files');
  const files = fi === -1 ? [] : argv.slice(fi + 1).filter((a) => !a.startsWith('--'));
  const res = run({ write, verbose, files });
  process.exit(res.errors.length ? 1 : 0);
}

module.exports = { run, extractCalls, renderBlock, BLOCK_RE };

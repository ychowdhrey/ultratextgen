#!/usr/bin/env node
/*
 * dump-style-registry.js — build-time bridge between the JS style registry
 * and (a) the per-style OG card generator (Python) and (b) the homepage
 * middleware's ?style= link-preview swap.
 *
 * Everything styled here goes through the real renderer (renderAny), never a
 * re-implementation of its parsing — the per-character maps for `map` styles
 * are built by rendering each character individually, so wrapped forms
 * (⦅A⦆, →A←) and array-backed styles come out exactly as the site renders
 * them, and this file can never drift from renderer.js.
 *
 * Outputs:
 *   data/og_style_registry.json   — for scripts/generate-style-og-cards.py
 *   functions/_og-style-data.js    — imported by functions/_middleware.js
 */
"use strict";

global.window = {};
require("../styles.js");
// renderer.js reaches some browser globals bare (textStyles at renderer.js
// ~L592) — in a browser those resolve via window; in Node they must be real
// globals or renderAny throws inside procedures and the style silently
// samples as plain text (15 styles did exactly that on the first run).
global.textStyles = global.window.textStyles;
require("../renderer.js");
global.UltraTextGenRender = global.window.UltraTextGenRender;

const fs = require("fs");
const path = require("path");

const styles = window.textStyles || {};
const render = window.UltraTextGenRender;
if (!render || !Object.keys(styles).length) {
  console.error("styles.js / renderer.js failed to load");
  process.exit(1);
}

const SAMPLE = "Abc def 123";
const ALPHABET = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789";

const registry = [];
const middleware = {};

for (const [name, style] of Object.entries(styles)) {
  if (!style || !style.slug) continue;
  let sample;
  try {
    sample = render.renderAny(SAMPLE, style);
  } catch (e) {
    sample = SAMPLE;
  }
  if (!sample || !String(sample).trim()) sample = SAMPLE;

  // The share URL carries the raw slug, but the recipient side (script.js)
  // and the middleware both normalize before comparing — a handful of
  // registry slugs use underscores. OG assets are keyed/named normalized.
  const key = String(style.slug).toLowerCase().replace(/_/g, "-");
  const entry = { slug: style.slug, key, name, type: style.type || "map", sample };

  // Per-character map for deterministic, order-preserving styles only:
  // `map` substitutes positionally and `redact` per character. Procedures
  // can be random (zalgo), decorators wrap the whole string, and the
  // `function` family reverses order (upside-down) — a per-char map would
  // misrepresent all three, so they fall back to the plain-text title.
  if (style.type === "map" || style.type === "redact") {
    const map = {};
    let ok = true;
    for (const ch of ALPHABET) {
      let out;
      try {
        out = render.renderAny(ch, style);
      } catch (e) {
        ok = false;
        break;
      }
      if (out && out !== ch) map[ch] = out;
    }
    if (ok && Object.keys(map).length) entry.map = map;
  }

  registry.push(entry);
  middleware[key] = {
    name,
    img: "/assets/og/style/" + key + ".png",
    map: entry.map || null,
  };
}

registry.sort((a, b) => a.slug.localeCompare(b.slug));

fs.writeFileSync(
  path.join(__dirname, "..", "data", "og_style_registry.json"),
  JSON.stringify(registry, null, 1) + "\n"
);

const banner =
  "// GENERATED by scripts/dump-style-registry.js — do not edit by hand.\n" +
  "// Rebuild with: node scripts/dump-style-registry.js\n" +
  "// Consumed by functions/_middleware.js for the ?style= link-preview swap.\n";
fs.writeFileSync(
  path.join(__dirname, "..", "functions", "_og-style-data.js"),
  banner + "export const STYLE_OG = " + JSON.stringify(middleware) + ";\n"
);

console.log(
  "dumped " + registry.length + " styles (" +
  registry.filter((r) => r.map).length + " with char maps) -> " +
  "data/og_style_registry.json + functions/_og-style-data.js"
);

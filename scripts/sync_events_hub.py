import html
import json
import pathlib
import re
import sys

SCRIPT_DIR = pathlib.Path(__file__).resolve().parent
REPO = SCRIPT_DIR.parent
SPEC_DIR = REPO / "data" / "event_page_specs"
HUB = REPO / "events" / "index.html"

sys.path.insert(0, str(SCRIPT_DIR / "lib"))
from event_occurrence import format_date, is_lunar, next_occurrences  # noqa: E402

START = "<!-- HUB-CARDS:START (generated by scripts/sync_events_hub.py — do not hand-edit) -->"
END = "<!-- HUB-CARDS:END -->"


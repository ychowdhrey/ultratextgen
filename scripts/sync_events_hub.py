#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""sync_events_hub.py — rebuild the /events/ hub card grid from the specs.

The hub listed its events in frozen build order, so Chinese New Year led the
page all through August — the least useful card for the next six months — and
every card was text-only and visually identical. It was also hand-maintained,
so a new event page could ship without ever appearing on its own hub.

This regenerates the grid between the HUB-CARDS markers, ordered by whichever
event comes next, with a date chip and one emoji per card. Deterministic dates
are baked in; lunar events (Eid, Chinese New Year) carry their rule instead and
are filled in and re-sorted at runtime by js/events/eventDates.js, for the same
reason as the per-page date line — ICU in the browser is the only source for
those dates this repo can honestly use.

Usage
-----
    python3 scripts/sync_events_hub.py            # report only
    python3 scripts/sync_events_hub.py --write    # apply
"""


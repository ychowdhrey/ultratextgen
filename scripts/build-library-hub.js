#!/usr/bin/env node
'use strict';

/**
 * build-library-hub.js — give a locale library hub the shared browse UI.
 *
 * WHAT IT DOES
 * ------------
 * For each locale hub that is missing the browse UI, it inserts the controls
 * (search, facet pills, A–Z bar), a pre-rendered `#libDirectory` listing every
 * page in that locale's own library directory, the empty state and the
 * back-to-top control — then declares the page's data and loads
 * `js/library/library-hub.js`.
 *
 * WHY IT IS A GENERATOR AND NOT TWELVE HAND EDITS
 * -----------------------------------------------
 * Because hand-building hubs is what broke them. On 2026-07-14 three commits in
 * one rollout batch each built two hubs from two different templates — fr rich
 * and ja plain, es rich and th plain, tr rich and vi plain — and a month later
 * zh-tw was built plain again. A generator plus `check-library-hub-parity.js`
 * removes the step where that judgement gets made per page.
 *
 * WHERE EVERY STRING COMES FROM
 * -----------------------------
 * Nothing is translated here. Entry titles, descriptions and previews are read
 * from each locale page's own markup (`scripts/lib/library-hub-data.js`); facet
 * classification is inherited from the page's English parent and rendered
 * through that locale's own vocabulary in `data/library_hub_i18n.json`; UI copy
 * is that file's `ui` block. So a generated hub cannot introduce English its own
 * pages did not already carry — which is what keeps `check:locale-translation`
 * green on the output.
 *
 * The directory is pre-rendered rather than left to the browser for the reason
 * `build-library-directory.js` documents: crawlers that fetch HTML without
 * running JavaScript — GPTBot, ClaudeBot, Amazonbot, Google-Extended, all
 * invited by robots.txt — would otherwise see a hub page linking nothing.
 * Static and runtime markup come from the same `renderDirectory()`, so they
 * cannot drift.
 *
 * Usage:
 *   node scripts/build-library-hub.js                 # all eligible locales
 *   node scripts/build-library-hub.js --locale ja     # one locale
 *   node scripts/build-library-hub.js --check         # verify, exit 1 on drift
 */

const fs   = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const HUB  = require(path.join(ROOT, 'js', 'library', 'library-hub.js'));
const DATA = require(path.join(ROOT, 'scripts', 'lib', 'library-hub-data.js'));
const I18N = require(path.join(ROOT, 'data', 'library_hub_i18n.json'));

const args = process.argv.slice(2);
const CHECK = args.includes('--check');
const localeIdx = args.indexOf('--locale');
const ONLY = localeIdx !== -1 ? args[localeIdx + 1] : null;

const MARK_OPEN  = '<!-- library-hub:begin (generated by scripts/build-library-hub.js) -->';
const MARK_CLOSE = '<!-- library-hub:end -->';

function esc(s) { return HUB.escHtml(s); }

/** The controls + directory + empty state + back-to-top, as one block. */
function browseMarkup(cfg, directoryHtml) {
  const t = cfg.i18n;
  const facets = [
    ['type', 'libTypeFilters'],
    ['subject', 'libSubjectFilters'],
    ['useCases', 'libUseCaseFilters'],
    ['platforms', 'libPlatformFilters'],
  ];
  const rows = facets
    .filter(([key]) => cfg.items.some((i) => i[key] && (!Array.isArray(i[key]) || i[key].length)))
    .map(([, id]) => `      <div class="lib-filter-row" id="${id}"></div>`)
    .join('\n');

  return `${MARK_OPEN}
<div class="lib-controls" id="libControls">
  <div class="lib-search-wrap">
    <label class="u-visually-hidden" for="libSearch">${esc(t.searchLabel)}</label>
    <input type="search" id="libSearch" autocomplete="off"
           placeholder="${esc(t.searchPlaceholder)}" aria-label="${esc(t.searchLabel)}">
  </div>
  <div class="lib-filters">
${rows}
  </div>
  <div class="lib-controls-foot">
    <p class="lib-result-count" id="libResultCount" hidden></p>
    <button type="button" class="lib-clear" id="libClearFilters">${esc(t.clearFilters)}</button>
  </div>
  <nav class="lib-alpha-bar" id="libAlphaBar" aria-label="${esc(t.alphaJump)}"></nav>
</div>

<main class="lib-directory" id="libDirectory" aria-label="${esc(t.directoryLabel)}" data-static-directory>
${directoryHtml}
</main>

<div class="lib-empty" id="libEmpty" role="status" aria-live="polite" hidden>
  <p class="lib-empty-title">${esc(t.emptyTitle)}</p>
  <p class="lib-empty-body">${esc(t.emptyBody)}</p>
  <button type="button" class="lib-clear" id="libEmptyReset">${esc(t.emptyReset)}</button>
</div>

<button type="button" class="lib-back-top" id="libBackTop"
        aria-label="${esc(t.backTop)}" title="${esc(t.backTop)}">↑</button>

<script>
window.UTG_LIBRARY_HUB = ${JSON.stringify({
    locale: cfg.locale,
    basePath: cfg.basePath,
    i18n: cfg.i18n,
    items: cfg.items,
  }, null, 1)};
</script>
<script src="/js/library/library-hub.js" defer></script>
${MARK_CLOSE}`;
}

/**
 * Insert (or replace) the block on a hub page.
 *
 * The browse tool goes above the hub's own curated sections rather than
 * replacing them — those groupings are hand-written editorial copy and are not
 * this script's to discard.
 *
 * The anchor is structural, not decorative: close of the *intro* section, i.e.
 * the second `</section>` (hero first, then the intro prose). Anchoring on
 * `<div class="section-divider">` looked right on the hubs that have one and
 * silently excluded `ar`, which structures the same page with bare
 * `editorial-section` elements and no dividers at all.
 */
function place(html, block) {
  const existing = new RegExp(
    escapeRe(MARK_OPEN) + '[\\s\\S]*?' + escapeRe(MARK_CLOSE)
  );
  if (existing.test(html)) return html.replace(existing, block);

  const closes = [];
  const re = /<\/section>/g;
  let m;
  while ((m = re.exec(html)) !== null) closes.push(m.index + m[0].length);
  if (closes.length === 0) return null;

  // Second </section> when the page has hero + intro; otherwise the first.
  const at = closes.length >= 2 ? closes[1] : closes[0];
  return html.slice(0, at) + '\n\n' + block + '\n' + html.slice(at);
}

function escapeRe(s) { return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'); }

function localesToBuild() {
  if (ONLY) return [ONLY];
  return Object.keys(I18N).filter((k) => !k.startsWith('_'));
}

function main() {
  let changed = 0, drift = 0, skipped = 0, failed = 0;

  for (const locale of localesToBuild()) {
    const rel = `${locale}/library/index.html`;
    const abs = path.join(ROOT, rel);
    if (!fs.existsSync(abs)) { console.log(`  skip  ${rel} — no such hub`); skipped++; continue; }

    const conf = I18N[locale];
    if (!conf) { console.error(`ERROR ${rel} — no entry in data/library_hub_i18n.json`); failed++; continue; }

    const missing = HUB.I18N_KEYS.filter((k) => !conf.ui[k]);
    if (missing.length) {
      console.error(`ERROR ${rel} — i18n block missing: ${missing.join(', ')}`);
      failed++; continue;
    }

    const inv = DATA.buildInventory(locale, conf.labels);
    if (inv.missingLabels.size) {
      console.error(`ERROR ${rel} — no ${locale} label for: ${[...inv.missingLabels].join(', ')}`);
      failed++; continue;
    }

    const cfg = {
      locale,
      basePath: `/${locale}/library/`,
      i18n: conf.ui,
      items: inv.items,
    };

    const directory = HUB.renderDirectory(cfg, cfg.items);
    const block = browseMarkup(cfg, directory);

    const html = fs.readFileSync(abs, 'utf8');
    const updated = place(html, block);
    if (updated === null) {
      console.error(`ERROR ${rel} — no insertion anchor found (needs at least one </section>)`);
      failed++; continue;
    }

    if (updated === html) {
      console.log(`  ok    ${rel} — already current (${cfg.items.length} entries)`);
      continue;
    }

    if (CHECK) {
      console.error(`DRIFT ${rel} — browse UI missing or stale (${cfg.items.length} entries)`);
      drift++;
      continue;
    }

    fs.writeFileSync(abs, updated, 'utf8');
    console.log(`  wrote ${rel} — ${cfg.items.length} entries, ` +
      `${(directory.match(/href=/g) || []).length} links pre-rendered`);
    changed++;
  }

  if (CHECK) {
    if (drift) {
      console.error(`\n${drift} hub(s) out of date. Run: node scripts/build-library-hub.js`);
      process.exit(1);
    }
    console.log('\nAll generated library hubs are current.');
    return;
  }
  console.log(`\nDone. ${changed} hub(s) updated, ${skipped} skipped, ${failed} failed.`);
  if (failed) process.exit(1);
}

main();

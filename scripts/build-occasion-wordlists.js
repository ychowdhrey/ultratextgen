#!/usr/bin/env node
'use strict';
/**
 * build-occasion-wordlists.js
 *
 * Writes the "Occasions" chip group into the word-list presets of the word
 * scramble and spelling makers, from the word-search hand-off words in the
 * English event specs (data/event_page_specs/<slug>.json). One copy of each
 * list: the event page's "word search" card and the maker's chip read the
 * same spec, and js/printables/spelling.test.js fails when they differ.
 *
 * The word search maker is left out on purpose while its redesign readout
 * (30-day control-usage shares, evaluated 2026-12-07) is running: a new chip
 * group there would change what that readout measures.
 *
 * Chips are in calendar order. The region between the markers is generated;
 * never edit it by hand.
 *
 * Usage:
 *   node scripts/build-occasion-wordlists.js           # check, exit 1 on drift
 *   node scripts/build-occasion-wordlists.js --write   # rewrite the regions
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const SPECS = path.join(ROOT, 'data', 'event_page_specs');
const PAGES = [
  { rel: 'printables/word-scramble-maker/index.html', box: 'pt-sc-input' },
  { rel: 'printables/spelling-worksheet-generator/index.html', box: 'pt-sp-input' }
];
const BEGIN = '<!-- BEGIN occasion word lists: generated by scripts/build-occasion-wordlists.js from data/event_page_specs, do not edit -->';
const END = '<!-- END occasion word lists -->';
const INDENT = '            ';

/** Every English spec whose experience hands a fixed word list to the word
 *  search, as { slug, name, words, month, day } sorted by calendar date. */
function occasions() {
  const out = [];
  for (const file of fs.readdirSync(SPECS).sort()) {
    if (!file.endsWith('.json') || file.startsWith('_')) continue;
    const spec = JSON.parse(fs.readFileSync(path.join(SPECS, file), 'utf8'));
    if ((spec.language || 'en') !== 'en') continue;
    const handoffs = (spec.experience && spec.experience.handoffs) || [];
    const ws = handoffs.find((h) => h.target === 'word_search' && h.params && Array.isArray(h.params.words));
    if (!ws || !ws.params.words.length) continue;
    const occ = spec.occurrence || {};
    // nth-weekday dates sort by month and the earliest day the nth weekday can fall on.
    const day = occ.type === 'fixed' ? occ.day : ((occ.n || 1) - 1) * 7 + 1;
    out.push({ slug: spec.slug, name: spec.event_name, words: ws.params.words, month: occ.month || 13, day: day || 1 });
  }
  return out.sort((a, b) => a.month - b.month || a.day - b.day || a.slug.localeCompare(b.slug));
}

const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;');

function block(list) {
  const chips = list.map((o) =>
    `${INDENT}    <button type="button" class="pt-gen-preset pt-gen-wordset" data-set="occasion-${esc(o.slug)}" data-words="${esc(o.words.join('|'))}" aria-pressed="false">${esc(o.name)} <small>${o.words.length} words</small></button>`);
  return [
    `${INDENT}${BEGIN}`,
    `${INDENT}<div class="pt-wordlist-group">`,
    `${INDENT}  <p class="pt-wordlist-group-label">Occasions</p>`,
    `${INDENT}  <div class="pt-segment" role="group" aria-label="Occasions">`,
    ...chips,
    `${INDENT}  </div>`,
    `${INDENT}</div>`,
    `${INDENT}${END}`
  ].join('\n');
}

function render(html, rel, box, want) {
  const open = `<details class="pt-field pt-wordlist-presets" data-list-for="${box}">`;
  const start = html.indexOf(open);
  if (start === -1) throw new Error(`${rel}: no word-list presets bound to #${box}`);
  const close = html.indexOf('</details>', start);
  const inside = html.slice(start, close);
  const b = inside.indexOf(BEGIN);
  if (b !== -1) {
    const lineStart = html.lastIndexOf('\n', start + b) + 1;
    const e = html.indexOf(END, start + b);
    if (e === -1 || e > close) throw new Error(`${rel}: BEGIN marker without END`);
    return html.slice(0, lineStart) + want + html.slice(e + END.length);
  }
  // First run: the group goes last, just before </details>.
  const lineStart = html.lastIndexOf('\n', close) + 1;
  return html.slice(0, lineStart) + want + '\n' + html.slice(lineStart);
}

function main() {
  const write = process.argv.includes('--write');
  const list = occasions();
  if (!list.length) {
    console.error('build-occasion-wordlists: UNKNOWN, no event spec hands a word list to the word search');
    return 3;
  }
  const want = block(list);
  let drift = 0;
  for (const { rel, box } of PAGES) {
    const file = path.join(ROOT, rel);
    const html = fs.readFileSync(file, 'utf8');
    const next = render(html, rel, box, want);
    if (next === html) continue;
    drift++;
    if (write) { fs.writeFileSync(file, next); console.log(`updated ${rel}`); }
    else console.error(`${rel}: occasion word lists differ from data/event_page_specs (run with --write)`);
  }
  console.log(`build-occasion-wordlists: ${list.map((o) => o.slug).join(', ')} on ${PAGES.length} pages, ${drift} ${write ? 'updated' : 'out of date'}`);
  return write ? 0 : (drift ? 1 : 0);
}

process.exit(main());

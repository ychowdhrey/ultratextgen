#!/usr/bin/env python3
"""Generate js/skintone/skinToneExpected.json: the standard toned forms of every tile in an opted-in section.

The skin-tone picker (symbol-explorer.js, the @skin-tone block) decides with a rule which tiles it tones and
how. This file is the independent answer from Unicode itself: for every tile inside a section[data-skin-tone] on
any page, the five fully-qualified toned sequences that emoji-test.txt lists for it, or null when it has none.
js/skintone/skinTone.test.js runs the shipped rule against it.

  python3 scripts/build-skin-tone-fixture.py [path-or-url-to-emoji-test.txt]          # write
  python3 scripts/build-skin-tone-fixture.py --check [path-or-url-to-emoji-test.txt]  # exit 1 when stale

Re-run after opting a new section in, and when a new Emoji version publishes. Generated: never hand-edit.
"""
import glob, html, json, os, re, sys, urllib.request

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
OUT = os.path.join(ROOT, 'js', 'skintone', 'skinToneExpected.json')
DEFAULT = 'https://www.unicode.org/Public/emoji/latest/emoji-test.txt'
MODS = [chr(c) for c in range(0x1F3FB, 0x1F400)]
VS16 = '️'


def read(src):
    if re.match(r'https?://', src):
        return urllib.request.urlopen(src, timeout=60).read().decode('utf-8')
    return open(src, encoding='utf-8').read()


def toned_index(text):
    """key (sequence with every tone and VS16 removed) -> {modifier: fully-qualified sequence}, single-tone only."""
    idx = {}
    for line in text.splitlines():
        if not line or line.startswith('#'):
            continue
        left = line.split('#', 1)[0]
        cps, status = [x.strip() for x in left.split(';')]
        if status != 'fully-qualified':
            continue
        seq = ''.join(chr(int(h, 16)) for h in cps.split())
        tones = {c for c in seq if c in MODS}
        if len(tones) != 1:
            continue
        key = ''.join(c for c in seq if c not in MODS and c != VS16)
        idx.setdefault(key, {})[tones.pop()] = seq
    return idx


def opted_tiles():
    tiles = set()
    for f in glob.glob(os.path.join(ROOT, '**', 'index.html'), recursive=True):
        if 'node_modules' in f:
            continue
        s = open(f, encoding='utf-8').read()
        if 'data-skin-tone' not in s:
            continue
        for m in re.finditer(r'<section class="mood-explainers" id="[^"]+" data-skin-tone>(.*?)</section>', s, re.S):
            tiles.update(html.unescape(x) for x in re.findall(r'data-symbol="([^"]*)"', m.group(1)))
    return tiles


def build(text):
    ver = re.search(r'^# Version:\s*(\d+\.\d+)', text, re.M)
    if not ver:
        raise SystemExit('not an emoji-test.txt file')
    idx = toned_index(text)
    out = {}
    for t in sorted(opted_tiles()):
        key = ''.join(c for c in t if c != VS16)
        forms = idx.get(key)
        out[t] = [forms[m] for m in MODS] if forms and len(forms) == 5 else None
    return {'_readme': 'GENERATED by scripts/build-skin-tone-fixture.py from Unicode emoji-test.txt. Do not hand-edit.',
            'emoji_version': ver.group(1), 'tiles': out}


if __name__ == '__main__':
    args = [a for a in sys.argv[1:] if not a.startswith('--')]
    d = build(read(args[0] if args else DEFAULT))
    new = json.dumps(d, ensure_ascii=False, indent=1) + '\n'
    if '--check' in sys.argv:
        cur = open(OUT, encoding='utf-8').read() if os.path.exists(OUT) else ''
        sys.exit(0 if cur == new else 1)
    open(OUT, 'w', encoding='utf-8').write(new)
    n = sum(1 for v in d['tiles'].values() if v)
    print(f'wrote {os.path.relpath(OUT, ROOT)}: Emoji {d["emoji_version"]}, {len(d["tiles"])} opted-in tiles, {n} with five standard toned forms')

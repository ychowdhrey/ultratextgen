#!/usr/bin/env python3
"""Generate data/unicode_assigned_ranges.json from the Unicode Character Database `DerivedAge.txt`.

Why this exists: Python's `unicodedata` lags the Unicode release this site writes about (a new currency
sign or emoji reads as unassigned there), and the symbol-page gate must know which code points are
assigned *today*. The output is generated, never hand-edited; re-run it when a Unicode version publishes.

  python3 scripts/build-unicode-assigned.py [path-or-url-to-DerivedAge.txt]   # default: UCD "latest"
  python3 scripts/build-unicode-assigned.py --check                            # exit 1 when the file differs from the source
"""
import json, os, re, sys, urllib.request

OUT = os.path.join(os.path.dirname(__file__), "..", "data", "unicode_assigned_ranges.json")
DEFAULT = "https://www.unicode.org/Public/UCD/latest/ucd/DerivedAge.txt"


def read(src):
    if re.match(r"https?://", src):
        return urllib.request.urlopen(src, timeout=60).read().decode("utf-8")
    return open(src, encoding="utf-8").read()


def build(text):
    ver = re.search(r"DerivedAge-(\d+\.\d+\.\d+)\.txt", text)
    if not ver:
        raise SystemExit("not a DerivedAge file (no version header)")
    rng = []
    for line in text.splitlines():
        line = line.split("#")[0].strip()
        if not line:
            continue
        r, _age = [x.strip() for x in line.split(";")]
        a, b = (r.split("..") + [r])[:2] if ".." in r else (r, r)
        rng.append([int(a, 16), int(b, 16)])
    rng.sort()
    merged = []
    for a, b in rng:
        if merged and a <= merged[-1][1] + 1:
            merged[-1][1] = max(merged[-1][1], b)
        else:
            merged.append([a, b])
    return {"_readme": "GENERATED by scripts/build-unicode-assigned.py from the Unicode Character Database DerivedAge.txt. Do not hand-edit.",
            "version": ver.group(1), "ranges": merged}


if __name__ == "__main__":
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    d = build(read(args[0] if args else DEFAULT))
    new = json.dumps(d, indent=0) + "\n"
    if "--check" in sys.argv:
        cur = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        sys.exit(0 if cur == new else 1)
    open(OUT, "w", encoding="utf-8").write(new)
    print(f"wrote {OUT}: Unicode {d['version']}, {len(d['ranges'])} ranges")

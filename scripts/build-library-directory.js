#!/usr/bin/env node
'use strict';

/**
 * build-library-directory.js
 *
 * Pre-renders the unfiltered /library/ directory into `library/index.html` as
 * real static HTML.
 *
 * WHY
 * ---
 * `library/index.html` is the browse hub for every `library/*` collection page,
 * and its entries used to exist only as a JavaScript array rendered into
 * `#libDirectory` at runtime. Crawlers that fetch HTML without executing
 * JavaScript — GPTBot, ClaudeBot, Amazonbot, meta-externalagent,
 * Google-Extended, every one of which `robots.txt` explicitly invites — saw a
 * hub page with zero links to the pages it is a hub for.
 *
 * HOW
 * ---
 * Nothing here re-implements the markup. The script reads `library/index.html`,
 * pulls out
 *
 *   1. the page's own `LIBRARY` array, and
 *   2. the page's own `directoryHtml()` / `escHtml()` source, delimited by
 *      `library-directory-markup:begin` / `:end`
 *
 * runs (2) over (1), and writes the result into the `#libDirectory` element.
 * The static markup and the runtime markup therefore cannot drift: they are
 * produced by the same function over the same data. At runtime the page keeps
 * the pre-rendered DOM until a filter changes what should be shown, so the
 * search / alphabet / pill behaviour is unchanged.
 *
 * Usage:
 *   node scripts/build-library-directory.js            # write
 *   node scripts/build-library-directory.js --check    # verify, exit 1 on drift
 *   npm run build:library-directory
 *   npm run check:library-directory
 */

const fs = require('fs');
const path = require('path');
const vm = require('vm');

const ROOT = path.resolve(__dirname, '..');
const PAGE = path.join(ROOT, 'library', 'index.html');

const BEGIN_MARKER = '/* library-directory-markup:begin */';
const END_MARKER = '/* library-directory-markup:end */';

const GENERATED_NOTE =
  '<!-- Directory entries below are generated by scripts/build-library-directory.js ' +
  'from this page\'s own LIBRARY array. Do not hand-edit: run ' +
  '`npm run build:library-directory`. They are static so non-JS crawlers see every ' +
  'library link; the page\'s script reuses this DOM until a filter changes it. -->';

const MAIN_RE =
  /<main class="lib-directory" id="libDirectory" aria-label="Library directory"[^>]*>[\s\S]*?<\/main>/;

/**
 * Slice out a bracketed literal starting at `start` (which must index the
 * opening bracket), skipping over string literals, template literals,
 * comments and regex-looking slashes so brackets inside them don't count.
 */
function sliceBalanced(src, start) {
  const open = src[start];
  const close = open === '[' ? ']' : '}';
  let depth = 0;

  for (let i = start; i < src.length; i++) {
    const ch = src[i];

    if (ch === '"' || ch === "'" || ch === '`') {
      const quote = ch;
      i++;
      while (i < src.length) {
        if (src[i] === '\\') { i += 2; continue; }
        if (src[i] === quote) break;
        i++;
      }
      continue;
    }

    if (ch === '/' && src[i + 1] === '/') {
      i = src.indexOf('\n', i);
      if (i === -1) break;
      continue;
    }

    if (ch === '/' && src[i + 1] === '*') {
      i = src.indexOf('*/', i + 2);
      if (i === -1) break;
      i += 1;
      continue;
    }

    if (ch === open) depth++;
    else if (ch === close) {
      depth--;
      if (depth === 0) return src.slice(start, i + 1);
    }
  }

  throw new Error('unbalanced ' + open + ' starting at offset ' + start);
}

function extractLibrary(html) {
  const decl = 'var LIBRARY = ';
  const at = html.indexOf(decl);
  if (at === -1) throw new Error('could not find `var LIBRARY = ` in ' + PAGE);
  const bracket = html.indexOf('[', at);
  const literal = sliceBalanced(html, bracket);

  const items = vm.runInNewContext('(' + literal + ')', Object.create(null), {
    timeout: 5000
  });
  if (!Array.isArray(items) || items.length === 0) {
    throw new Error('LIBRARY did not evaluate to a non-empty array');
  }
  return items;
}

function extractMarkupFn(html) {
  const begin = html.indexOf(BEGIN_MARKER);
  const end = html.indexOf(END_MARKER);
  if (begin === -1 || end === -1 || end < begin) {
    throw new Error(
      'could not find the ' + BEGIN_MARKER + ' … ' + END_MARKER +
      ' block in ' + PAGE
    );
  }
  const source = html.slice(begin + BEGIN_MARKER.length, end);

  const sandbox = Object.create(null);
  const factory = vm.runInNewContext(
    '(function () { "use strict";\n' + source + '\nreturn directoryHtml; })',
    sandbox,
    { timeout: 5000 }
  );
  const fn = factory();
  if (typeof fn !== 'function') {
    throw new Error('the markup block did not define directoryHtml()');
  }
  return fn;
}

/**
 * Break the single-line runtime string onto one line per entry so the
 * generated block stays reviewable in a diff. Only whitespace between
 * block-level boxes is introduced (`.lib-directory` and `.lib-letter-section`
 * are plain block containers), so rendering is unaffected.
 */
function formatForSource(html) {
  return html
    .split('</h2>').join('</h2>\n')
    .split('</article>').join('</article>\n')
    .split('</section>').join('</section>\n')
    .trim();
}

function buildMain(html) {
  const items = extractLibrary(html);
  const directoryHtml = extractMarkupFn(html);
  const body = formatForSource(directoryHtml(items));

  return {
    count: items.length,
    markup:
      '<main class="lib-directory" id="libDirectory" aria-label="Library directory" data-static-directory>\n' +
      GENERATED_NOTE + '\n' +
      body + '\n' +
      '</main>'
  };
}

function main() {
  const check = process.argv.includes('--check');
  const html = fs.readFileSync(PAGE, 'utf8');

  if (!MAIN_RE.test(html)) {
    console.error('ERROR: could not find the #libDirectory <main> element in ' + PAGE);
    process.exit(1);
  }

  const built = buildMain(html);
  const next = html.replace(MAIN_RE, () => built.markup);

  const rel = path.relative(ROOT, PAGE);

  if (next === html) {
    console.log('library directory up to date — ' + built.count + ' static entries in ' + rel);
    return;
  }

  if (check) {
    console.error(
      'ERROR: ' + rel + ' is out of date with its own LIBRARY array.\n' +
      '       Run `npm run build:library-directory` and commit the result.'
    );
    process.exit(1);
  }

  fs.writeFileSync(PAGE, next);
  console.log('wrote ' + built.count + ' static directory entries into ' + rel);
}

main();

#!/usr/bin/env node
'use strict';

/**
 * build-llms-index.js — write (or verify) every llms.txt on the site.
 *
 *   node scripts/build-llms-index.js            # check (default), exit 1 on drift
 *   node scripts/build-llms-index.js --write    # generate
 *   node scripts/build-llms-index.js --list     # paths, sizes, link counts
 *
 * Same contract as scripts/build-static-footer.js and
 * scripts/build-library-directory.js: the output is committed, so the default
 * mode regenerates and compares. That comparison IS the drift protection —
 * a new locale, a new printable, a retired route, a page flipped to noindex or
 * a page that lost its hero tagline all change the generated bytes, and the
 * check then fails naming the file. `npm run build:llms -- --write` is always
 * the fix, and it belongs in the same PR as the change that moved it.
 *
 * It gates rather than informs (the call scripts/check-zalgo-decodes.js makes,
 * for the same reason): the tree is either current or it is not, so there is no
 * standing backlog for it to be permanently red against.
 *
 * `--write` also REMOVES an llms.txt the model no longer plans — a locale that
 * loses its last page, or a section that drops below the inline threshold —
 * because an orphaned index advertising deleted routes is worse than no index.
 * Only files this generator owns are ever removed; the walk looks for the exact
 * filename and nothing else.
 */

const fs = require('fs');
const path = require('path');
const L = require('./lib/llms-index');

const argv = process.argv.slice(2);
const WRITE = argv.includes('--write');
const LIST = argv.includes('--list');

function existingFiles() {
  const out = [];
  const walk = (dir, rel) => {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      if (entry.name.startsWith('.')) continue;
      const next = rel ? `${rel}/${entry.name}` : entry.name;
      if (entry.isDirectory()) {
        if (entry.name === 'node_modules') continue;
        walk(path.join(dir, entry.name), next);
      } else if (entry.name === L.FILE_NAME) {
        out.push(next);
      }
    }
  };
  walk(L.ROOT, '');
  return out.sort();
}

function main() {
  let result;
  try {
    result = L.build();
  } catch (err) {
    console.error(`❌ ${err.message}`);
    process.exit(1);
  }

  const problems = L.validate(result);
  const stats = L.fileStats(result.files);
  const planned = new Map(result.files.map((f) => [f.relPath, f.content]));
  const onDisk = existingFiles();

  if (LIST) {
    const width = Math.max(...stats.map((s) => s.relPath.length));
    for (const s of stats) {
      console.log(`${s.relPath.padEnd(width)}  ${String(s.links).padStart(5)} links  ${String(s.bytes).padStart(7)} bytes`);
    }
    const bytes = stats.reduce((n, s) => n + s.bytes, 0);
    console.log(`\n${stats.length} files, ${stats.reduce((n, s) => n + s.links, 0)} links, ${bytes} bytes total`);
  }

  if (problems.length) {
    console.error(`❌ llms.txt validation found ${problems.length} problem(s):`);
    for (const p of problems.slice(0, 60)) console.error(`   ${p}`);
    if (problems.length > 60) console.error(`   … and ${problems.length - 60} more`);
    process.exit(1);
  }

  const changed = [];
  const removed = [];
  for (const [relPath, content] of planned) {
    let current = null;
    try {
      current = fs.readFileSync(path.join(L.ROOT, relPath), 'utf8');
    } catch { /* new file */ }
    if (current !== content) changed.push(relPath);
  }
  for (const relPath of onDisk) if (!planned.has(relPath)) removed.push(relPath);

  if (!WRITE) {
    if (!changed.length && !removed.length) {
      console.log(
        `✅ llms.txt tree current — ${stats.length} files, `
        + `${result.pages.length} pages, ${result.locales.size} languages.`
      );
      return;
    }
    console.error('❌ llms.txt tree is stale. Run: npm run build:llms -- --write');
    for (const relPath of changed.slice(0, 40)) console.error(`   changed: /${relPath}`);
    if (changed.length > 40) console.error(`   … and ${changed.length - 40} more changed`);
    for (const relPath of removed) console.error(`   no longer planned: /${relPath}`);
    process.exit(1);
  }

  for (const [relPath, content] of planned) {
    const abs = path.join(L.ROOT, relPath);
    fs.mkdirSync(path.dirname(abs), { recursive: true });
    fs.writeFileSync(abs, content, 'utf8');
  }
  for (const relPath of removed) fs.rmSync(path.join(L.ROOT, relPath));

  console.log(
    `✅ wrote ${planned.size} llms.txt files `
    + `(${changed.length} changed, ${removed.length} removed) — `
    + `${result.pages.length} pages, ${result.locales.size} languages, `
    + `${result.skippedNoindex.length} noindex routes excluded.`
  );
}

if (require.main === module) main();

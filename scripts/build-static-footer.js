#!/usr/bin/env node
"use strict";

/**
 * build-static-footer.js
 *
 * Bake the site footer into every page as real, static HTML.
 *
 * WHY
 * ---
 * The footer is the site's densest block of internal links — every page's
 * nav hubs, popular tools, popular categories and company links, ~27 of
 * them, in the visitor's own language. Until now it existed only at
 * runtime: every page ships an empty `<footer class="footer">` shell (or no
 * footer at all) and footer.js fills it in on load.
 *
 * A browser runs that JS. The crawlers robots.txt explicitly invites —
 * GPTBot, ClaudeBot, Amazonbot, Google-Extended, meta-externalagent — do a
 * plain HTTP fetch and parse the response body. They execute nothing, so
 * they saw an empty shell and none of those links. Googlebot renders JS and
 * was fine; this closes the gap for everything that doesn't.
 *
 * The footer's "Explore" column carries the same destinations as the header
 * nav (home + guide/answers/usecase/category/library/printables/events), so
 * baking the footer alone gives a non-rendering crawler every hub the nav
 * would have given it. header.js is deliberately left untouched.
 *
 * HOW — one source of truth, not a copy
 * -------------------------------------
 * This script does NOT re-implement the footer markup. It executes the real
 * footer.js in a `vm` sandbox with a stub `document`, once per page, with
 * `window.location.pathname` set to that page's own URL — so every branch
 * footer.js has (locale detection, the /printables/ and /learn/ audience
 * footer, the five locales with a native printables hub) is exercised by
 * footer.js's own code, and the baked markup is byte-identical to what the
 * browser would have produced. A second implementation would drift; this
 * cannot.
 *
 * footer.js then becomes a no-op on these pages by its own existing guard:
 *
 *     if (document.querySelector(".footer-bottom")) return;
 *
 * That guard predates this script and was previously dead — no page had a
 * `.footer-bottom` — which is exactly the hook this needs. Nothing about
 * footer.js changes.
 *
 * DRIFT
 * -----
 * Because the markup is now committed, editing footer.js no longer updates
 * the pages. `--check` (npm run check:static-footer) recomputes and compares,
 * and is wired into .github/workflows/validate.yml as a gating step. It
 * doubles as the regression guard for stray page content inside <footer>
 * (see scripts/fix-footer-nested-content.py): any deviation from the
 * generated markup — including content that does not belong there — fails.
 *
 * Usage:
 *   node scripts/build-static-footer.js            # check (default), exit 1 on drift
 *   node scripts/build-static-footer.js --write    # bake
 *   node scripts/build-static-footer.js --write path/to/index.html
 */

const fs = require("fs");
const path = require("path");
const vm = require("vm");

const ROOT = path.resolve(__dirname, "..");

// The generated markup is delimited so a re-run can lift out exactly what it
// wrote and leave everything else alone. That matters: .footer-inner is not
// always empty — many pages hand-author a visible language switcher in there,
// and footer.js APPENDS its columns after it rather than replacing it. An
// earlier version of this script swapped the whole <footer> element out and
// silently deleted those switchers on ~700 pages.
const BEGIN =
  "<!-- BEGIN static footer — generated by scripts/build-static-footer.js from footer.js. " +
  "Do not edit by hand — run `npm run build:static-footer`. -->";
const END = "<!-- END static footer -->";

const esc = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
const GENERATED_RE = new RegExp("\\n?[ \\t]*" + esc(BEGIN) + "[\\s\\S]*?" + esc(END), "g");
const FOOTER_OPEN_RE = /<footer class="footer"[^>]*>/;
const INNER_OPEN = '<div class="footer-inner">';

const SKIP_DIRS = new Set(["node_modules", "assets", "scripts", "locales", "data", "docs", "reports"]);

// ── footer.js, compiled once, run per page ────────────────────────────────
const footerScript = new vm.Script(fs.readFileSync(path.join(ROOT, "footer.js"), "utf8"), {
  filename: "footer.js",
});

/**
 * Run the real footer.js for one URL path and return the markup it would
 * inject. The stub DOM answers every querySelector with null, which sends
 * footer.js down its "no existing footer element" branch — the one that
 * builds the complete <footer>…</footer> and hands it to body.appendChild.
 */
function footerFor(urlPath) {
  let captured = null;
  const makeEl = () => ({
    _h: "",
    set innerHTML(v) {
      this._h = v;
    },
    get innerHTML() {
      return this._h;
    },
    get firstChild() {
      return this._h;
    },
    appendChild() {},
    querySelector() {
      return null;
    },
  });
  const doc = {
    querySelector() {
      return null;
    },
    createElement() {
      return makeEl();
    },
    body: {
      appendChild(x) {
        captured = x;
      },
    },
  };
  const sandbox = { window: { location: { pathname: urlPath }, document: doc }, document: doc };
  vm.createContext(sandbox);
  footerScript.runInContext(sandbox);
  return captured;
}

function urlPathFor(rel) {
  const p = "/" + rel.replace(/index\.html$/, "");
  return p.endsWith("/") ? p : p + "/";
}

function findPages(explicit) {
  if (explicit.length) return explicit.map((p) => path.relative(ROOT, path.resolve(p)));
  const out = [];
  (function walk(dir) {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      if (entry.isDirectory()) {
        if (entry.name.startsWith(".") || SKIP_DIRS.has(entry.name)) continue;
        walk(path.join(dir, entry.name));
      } else if (entry.name === "index.html") {
        out.push(path.relative(ROOT, path.join(dir, entry.name)));
      }
    }
  })(ROOT);
  return out.sort();
}

/**
 * Index of the `</div>` that closes the .footer-inner opened at `from`.
 * Depth-aware, because the hand-authored language switchers inside it nest
 * their own divs.
 */
function innerCloseIndex(html, from) {
  const re = /<div\b[^>]*>|<\/div>/g;
  re.lastIndex = from;
  let depth = 1;
  let m;
  while ((m = re.exec(html))) {
    depth += m[0] === "</div>" ? -1 : 1;
    if (depth === 0) return m.index;
  }
  return -1;
}

/** Returns the page HTML with the generated footer in place. */
function bake(html, urlPath) {
  const generated = footerFor(urlPath);
  if (!generated) return { error: "footer.js produced nothing" };

  // The columns alone, without footer.js's own <footer>/.footer-inner wrapper —
  // that wrapper already exists on the page.
  const inner = generated.replace(/^<footer[^>]*>\s*<div class="footer-inner">/, "").replace(/<\/div><\/footer>$/, "");
  if (inner === generated) return { error: "unexpected footer.js output shape" };

  const block = BEGIN + "\n" + inner + "\n" + END;

  // Lift out whatever a previous run wrote, so re-runs are no-ops.
  let out = html.replace(GENERATED_RE, "");

  const open = FOOTER_OPEN_RE.exec(out);
  if (open) {
    const footerClose = out.indexOf("</footer>", open.index);
    let innerAt = out.indexOf(INNER_OPEN, open.index);
    if (innerAt !== -1 && footerClose !== -1 && innerAt > footerClose) innerAt = -1;

    if (innerAt === -1) {
      // <footer class="footer"></footer> with no inner wrapper. footer.js
      // creates one at runtime (`if (!inner) { … footer.appendChild(inner) }`);
      // do the same here rather than dropping the block outside the container
      // that gives it its max-width.
      if (footerClose === -1) return { error: "<footer> is not closed" };
      const wrapper = "\n" + INNER_OPEN + "\n" + block + "\n</div>\n";
      out = out.slice(0, footerClose) + wrapper + out.slice(footerClose);
      return { html: out };
    }
    const contentStart = innerAt + INNER_OPEN.length;
    const closeAt = innerCloseIndex(out, contentStart);
    if (closeAt === -1) return { error: ".footer-inner is not div-balanced" };
    // Append after any hand-authored content (the language switcher), exactly
    // where footer.js's inner.appendChild would have put it.
    const existing = out.slice(contentStart, closeAt).replace(/\s+$/, "");
    out = out.slice(0, contentStart) + existing + "\n" + block + "\n" + out.slice(closeAt);
  } else {
    // No footer element at all — footer.js builds a whole one for these.
    const idx = out.lastIndexOf("</body>");
    if (idx === -1) return { error: "no <footer> and no </body>" };
    const whole = '<footer class="footer">\n<div class="footer-inner">\n' + block + "\n</div>\n</footer>";
    out = out.slice(0, idx) + whole + "\n" + out.slice(idx);
  }
  return { html: out };
}

function main() {
  const argv = process.argv.slice(2);
  const write = argv.includes("--write");
  const files = argv.filter((a) => !a.startsWith("--"));
  const pages = findPages(files);

  let changed = 0;
  let ok = 0;
  const errors = [];
  const drifted = [];

  for (const rel of pages) {
    const abs = path.join(ROOT, rel);
    let html;
    try {
      html = fs.readFileSync(abs, "utf8");
    } catch {
      continue;
    }

    const result = bake(html, urlPathFor(rel));
    if (result.error) {
      errors.push([rel, result.error]);
      continue;
    }
    if (result.html === html) {
      ok++;
      continue;
    }
    changed++;
    drifted.push(rel);
    if (write) fs.writeFileSync(abs, result.html);
  }

  console.log(`Static footer — ${pages.length} page(s)`);
  console.log(`  already correct: ${ok}`);
  console.log(`  ${write ? "written" : "out of date"}: ${changed}`);
  if (errors.length) {
    console.log(`  errors: ${errors.length}`);
    for (const [rel, why] of errors.slice(0, 10)) console.log(`    ✗ ${rel} — ${why}`);
  }

  if (!write && changed) {
    for (const rel of drifted.slice(0, 15)) console.log(`    · ${rel}`);
    if (drifted.length > 15) console.log(`    … and ${drifted.length - 15} more`);
    console.log(
      "\nThe committed footer markup does not match what footer.js produces." +
        "\nFix: npm run build:static-footer"
    );
    return 1;
  }
  if (errors.length) return 1;
  if (!write) console.log("\nEvery page's static footer matches footer.js. ✓");
  return 0;
}

process.exit(main());

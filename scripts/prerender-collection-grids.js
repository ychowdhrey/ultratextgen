#!/usr/bin/env node
'use strict';
/**
 * prerender-collection-grids.js — make the copy-paste collections crawlable.
 *
 * WHAT IT FIXES
 * 898 pages render a collection section — the grid of ready-made combos with a
 * format picker and a Copy Collection button — and on every one of them that
 * section is the page's payload. All 898 shipped it as an empty
 * `<div id="…Container"></div>` plus an inline `GROUPS` array, built into DOM
 * by `UltraTextGen.buildGrids()` after load. CLAUDE.md's Discovery Model
 * section states the cost plainly: several search and AI crawlers execute no
 * JavaScript, so for those surfaces the page's payload did not exist.
 *
 * Measured 2026-09-10: 898 pages call buildGrids, exactly one call each, the
 * container always present, and 898 of 898 empty. (Two pages —
 * library/bow-ribbon-symbols and ja/library/ribon-kigou — carry unrelated
 * static `.flag-row` tiles in the same container and were miscounted as
 * pre-rendering their grids on a first read. Nothing pre-renders them.)
 *
 * HOW
 * It executes each page's own inline script against a capturing stub, so the
 * GROUPS it renders are the GROUPS the browser renders however the page builds
 * them (literal array, isoToFlag() calls, a map) — never a re-parse of the
 * source text. It then renders them with the SHIPPED renderer, sliced out of
 * symbol-explorer.js by scripts/lib/collection-grid-engine.js, so static and
 * runtime markup cannot drift. `buildGrids()` skips construction when it finds
 * a `.flag-grid-section` already present.
 *
 * The block is spliced into the raw HTML between markers, never round-tripped
 * through cheerio — for the reason docs/source-attribution.md §4 gives about
 * the JSON-LD fixer: re-serialising would reformat 898 files and bury the
 * real change in noise. The splice is verified against cheerio's own view of
 * the container before it is applied.
 *
 * USAGE
 *   node scripts/prerender-collection-grids.js              # report only
 *   node scripts/prerender-collection-grids.js --write
 *   node scripts/prerender-collection-grids.js --write --files a/index.html …
 *
 * Idempotent: a second run reports 0 updated.
 */

const fs = require('fs');
const path = require('path');
const vm = require('vm');
const cheerio = require('cheerio');
const { globSync } = require('glob');

const engine = require('./lib/collection-grid-engine.js');

const REPO = path.join(__dirname, '..');
const BEGIN = '<!-- BEGIN prerendered collections: generated by scripts/prerender-collection-grids.js, do not edit -->';
const END = '<!-- END prerendered collections -->';
const BLOCK_RE = /[ \t]*<!--\s*BEGIN prerendered collections\b[\s\S]*?<!--\s*END prerendered collections\s*-->\n?/;

/* ------------------------------------------------------------------ */
/* Extracting what the page actually renders                           */
/* ------------------------------------------------------------------ */

/** A callable, infinitely-chainable stub, so an inline script can poke at any
 *  DOM shape it likes without the extraction caring. */
function anyProxy() {
  const target = function () {};
  return new Proxy(target, {
    get(_t, key) {
      if (key === Symbol.toPrimitive) return () => '';
      if (key === Symbol.iterator) return function* () {};
      if (key === 'toString') return () => '';
      if (key === 'length') return 0;
      return anyProxy();
    },
    apply() { return anyProxy(); },
    has() { return true; }
  });
}

function withFallback(real) {
  return new Proxy(real, {
    get(t, key) {
      if (key in t) return t[key];
      return anyProxy();
    },
    has() { return true; }
  });
}

/**
 * Run every inline script that mentions buildGrids and report the calls it
 * makes. Returns [{ containerId, groups }].
 */
function extractCalls(html, lang) {
  const $ = cheerio.load(html);
  const calls = [];
  const ready = [];

  const ns = withFallback({
    buildGrids(containerId, groups) { calls.push({ containerId, groups }); },
    parseTwemoji() {},
    isoToFlag: engine.isoToFlag
  });
  const documentStub = withFallback({
    documentElement: withFallback({ lang }),
    addEventListener(evt, fn) { if (evt === 'DOMContentLoaded' && typeof fn === 'function') ready.push(fn); },
    removeEventListener() {},
    // A live element stub rather than null: three emoji-flags pages build
    // their country tile grid in the same script and would throw on
    // getElementById(...).appendChild before reaching buildGrids. Returning a
    // stub cannot smuggle in a call the browser would not make — every
    // captured container id is checked against the real HTML below, and a
    // page whose container does not exist is reported, not written.
    getElementById() { return anyProxy(); },
    querySelector() { return anyProxy(); },
    querySelectorAll() { return []; },
    createElement() { return anyProxy(); }
  });
  const windowStub = withFallback({ UltraTextGen: ns, document: documentStub });
  const sandbox = withFallback({
    window: windowStub, document: documentStub, UltraTextGen: ns,
    console: { log() {}, warn() {}, error() {} },
    setTimeout() { return 0; }, clearTimeout() {},
    JSON, Math, Object, Array, String, Number, Boolean, RegExp, Date, Map, Set
  });
  const context = vm.createContext(sandbox);

  $('script').each((_, el) => {
    if ($(el).attr('src')) return;
    const code = $(el).html() || '';
    if (!/\bbuildGrids\s*\(/.test(code)) return;
    vm.runInContext(code, context, { timeout: 5000 });
  });
  for (const fn of ready) fn();
  return calls;
}

/* ------------------------------------------------------------------ */
/* Splicing                                                            */
/* ------------------------------------------------------------------ */

/**
 * Byte offsets of a container element's inner content in raw HTML.
 * Depth-scans the element's own tag name, so nested divs are handled.
 */
function innerRange(html, id) {
  const attr = new RegExp(`<([a-zA-Z][\\w-]*)\\b[^>]*\\bid="${id.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}"`);
  const m = attr.exec(html);
  if (!m) return null;
  const tag = m[1];
  const openEnd = html.indexOf('>', m.index);
  if (openEnd === -1) return null;
  const re = new RegExp(`<${tag}\\b|</${tag}\\s*>`, 'gi');
  re.lastIndex = openEnd + 1;
  let depth = 1, hit;
  while ((hit = re.exec(html))) {
    if (hit[0][1] === '/') {
      depth -= 1;
      if (depth === 0) return { start: openEnd + 1, end: hit.index };
    } else {
      depth += 1;
    }
  }
  return null;
}

function renderBlock(groups, lang, indent) {
  const str = engine.UI_STRINGS[lang] || engine.UI_STRINGS.en;
  const formats = engine.activeFormatsFor(groups);
  const sections = groups.map((group, gi) => engine.gridSectionHTML(
    group, gi, formats[gi], str, engine.FORMATS, engine.COPY_ICON
  ));
  return `${indent}${BEGIN}\n` +
    sections.map((s) => indent + s).join('\n') +
    `\n${indent}${END}\n`;
}

/**
 * Append the block inside the container, preserving the file's own byte layout
 * around it: existing children untouched, the block indented like the
 * container's other children, the closing tag left where it was.
 */
function apply(html, containerId, block) {
  const stripped = html.replace(BLOCK_RE, '');
  const range = innerRange(stripped, containerId);
  if (!range) return null;

  const head = stripped.slice(0, range.start);
  const inner = stripped.slice(range.start, range.end);

  // Indentation of the line the container's own opening tag sits on.
  const openLine = head.slice(head.lastIndexOf('\n', head.length - 1) + 1);
  const openIndent = (/^[ \t]*/.exec(openLine) || [''])[0];

  // Whitespace the closing tag currently sits behind, and the body before it.
  // An empty container is written on one line (`<div id="x"></div>`), so there
  // is no existing indentation to preserve and the closing tag lines up with
  // the opening one instead.
  const trailing = /(?:^|\n)([ \t]*)$/.exec(inner);
  const closeIndent = inner.trim() === '' ? openIndent : (trailing ? trailing[1] : openIndent);
  let body = trailing ? inner.slice(0, inner.length - closeIndent.length) : inner;
  if (body && !body.endsWith('\n')) body += '\n';
  if (!body) body = '\n';

  // One step in from the container's own opening tag. Derived from the tag
  // rather than from a sampled child line, so 898 files indent identically
  // instead of inheriting whatever the nearest inner line happened to use.
  const childIndent = openIndent + '  ';

  return head + body + renderBlock(block.groups, block.lang, childIndent) +
    closeIndent + stripped.slice(range.end);
}

/* ------------------------------------------------------------------ */

function pagesWithGrids(files) {
  return files.filter((rel) => /\bbuildGrids\s*\(/.test(fs.readFileSync(path.join(REPO, rel), 'utf8')));
}

function run(opts) {
  const files = opts.files && opts.files.length
    ? opts.files
    : globSync('**/index.html', { cwd: REPO, ignore: ['node_modules/**'] });
  const targets = pagesWithGrids(files).sort();

  let updated = 0, current = 0;
  const errors = [];

  for (const rel of targets) {
    const abs = path.join(REPO, rel);
    const html = fs.readFileSync(abs, 'utf8');
    const $ = cheerio.load(html);
    const lang = ($('html').attr('lang') || 'en').slice(0, 2).toLowerCase();

    let calls;
    try {
      calls = extractCalls(html, lang);
    } catch (err) {
      errors.push(`${rel}: inline script would not run (${err.message})`);
      continue;
    }
    if (calls.length !== 1) {
      errors.push(`${rel}: expected exactly 1 buildGrids call, saw ${calls.length}`);
      continue;
    }
    const { containerId, groups } = calls[0];
    if (!Array.isArray(groups) || !groups.length) {
      errors.push(`${rel}: buildGrids called with no groups`);
      continue;
    }
    if (groups.some((g) => !g || typeof g.name !== 'string' || !Array.isArray(g.flags))) {
      errors.push(`${rel}: a group is missing name or flags`);
      continue;
    }

    const next = apply(html, containerId, { groups, lang });
    if (next === null) {
      errors.push(`${rel}: could not locate container #${containerId} in the raw HTML`);
      continue;
    }

    // Self-check: the splice must not have disturbed the container's existing
    // children, only appended to them.
    const before = cheerio.load(html.replace(BLOCK_RE, ''))(`#${containerId}`).children().length;
    const after = cheerio.load(next)(`#${containerId}`).children().length;
    if (after !== before + groups.length) {
      errors.push(`${rel}: splice changed child count to ${after}, expected ${before + groups.length}`);
      continue;
    }

    if (next === html) { current += 1; continue; }
    updated += 1;
    if (opts.write) fs.writeFileSync(abs, next);
    if (opts.verbose) console.log(`  ${opts.write ? 'wrote' : 'would write'} ${rel} (${groups.length} groups, ${lang})`);
  }

  console.log(`prerender-collection-grids — ${targets.length} page(s) with a collection grid`);
  console.log(`  ${current} already current, ${updated} ${opts.write ? 'updated' : 'would be updated'}`);
  if (errors.length) {
    console.log(`\n  ${errors.length} error(s):`);
    for (const e of errors) console.log(`    ${e}`);
  }
  return { targets: targets.length, updated, current, errors };
}

if (require.main === module) {
  const argv = process.argv.slice(2);
  const write = argv.includes('--write');
  const verbose = argv.includes('--verbose');
  const fi = argv.indexOf('--files');
  const files = fi === -1 ? [] : argv.slice(fi + 1).filter((a) => !a.startsWith('--'));
  const res = run({ write, verbose, files });
  process.exit(res.errors.length ? 1 : 0);
}

module.exports = { run, extractCalls, renderBlock, innerRange, apply, BLOCK_RE };

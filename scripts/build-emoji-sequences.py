#!/usr/bin/env python3
"""Generate data/emoji_sequences.json from the Unicode emoji `emoji-test.txt`.

Why this exists: the tile audit (scripts/audit-tile-unicode.py) has to tell a valid emoji sequence from a
malformed one, and the rest of the repo only knows which single code points are assigned
(data/unicode_assigned_ranges.json). The output is generated, never hand-edited; re-run it when a Unicode
or Emoji version publishes. Sequences are stored as space-separated hex code points, one entry each.

  python3 scripts/build-emoji-sequences.py [path-or-url-to-emoji-test.txt]   # default: Emoji "latest"
  python3 scripts/build-emoji-sequences.py --check [source]                  # exit 1 when the file differs
"""
import json, os, re, sys, urllib.request

OUT = os.path.join(os.path.dirname(__file__), "..", "data", "emoji_sequences.json")
DEFAULT = "https://www.unicode.org/Public/emoji/latest/emoji-test.txt"
KEEP = {"fully-qualified": "fully_qualified", "minimally-qualified": "minimally_qualified", "unqualified": "unqualified",
        "component": "component"}


def read(src):
    if re.match(r"https?://", src):
        return urllib.request.urlopen(src, timeout=60).read().decode("utf-8")
    return open(src, encoding="utf-8").read()


def build(text):
    ver = re.search(r"^# Version:\s*(\d+\.\d+)", text, re.M)
    if not ver:
        raise SystemExit("not an emoji-test.txt file (no '# Version:' header)")
    out = {v: [] for v in KEEP.values()}
    for line in text.splitlines():
        if not line or line.startswith("#"):
            continue
        left = line.split("#", 1)[0]
        cps, status = [x.strip() for x in left.split(";")]
        out[KEEP[status]].append(cps)
    if not out["fully_qualified"]:
        raise SystemExit("no fully-qualified sequences parsed")
    return {"_readme": "GENERATED by scripts/build-emoji-sequences.py from Unicode emoji-test.txt. Do not hand-edit.",
            "emoji_version": ver.group(1), **out}


if __name__ == "__main__":
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    d = build(read(args[0] if args else DEFAULT))
    new = json.dumps(d, separators=(",", ":")) + "\n"
    if "--check" in sys.argv:
        cur = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        sys.exit(0 if cur == new else 1)
    open(OUT, "w", encoding="utf-8").write(new)
    print(f"wrote {OUT}: Emoji {d['emoji_version']}, " + ", ".join(f"{len(v)} {k}" for k, v in d.items() if isinstance(v, list)))
